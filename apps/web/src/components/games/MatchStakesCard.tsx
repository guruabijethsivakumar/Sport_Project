import React, { useMemo } from 'react';
import {
  useMatchRatingPreview,
  useFeatureTeamSuggestion,
  type PreviewMatchPayload,
  type MatchPreviewResponse,
} from '@playmatch/shared';
import { useAuth, sharedApiClient } from '../../auth/AuthContext';
import { Card, CardHeader, CardTitle, CardContent } from '../ui/Card';
import { Badge } from '../ui/Badge';
import { Icon } from '../ui/Icon';

export interface MatchStakesCardProps {
  gameId: string;
  sportKey: string;
  isCancelled?: boolean;
  roster?: {
    joined?: Array<{ userId: string; displayName?: string; rating?: number }>;
  };
  onExplainRatings?: () => void;
  className?: string;
}

export function MatchStakesCard({
  gameId,
  sportKey,
  isCancelled = false,
  roster,
  onExplainRatings,
  className = '',
}: MatchStakesCardProps) {
  const auth = useAuth?.();
  const client = auth?.client || sharedApiClient;

  // Retrieve suggested balanced teams for the game if available
  const { data: teamSuggestion, isLoading: isTeamSuggestionLoading } =
    useFeatureTeamSuggestion(client, gameId, {
      enabled: Boolean(gameId && !isCancelled),
    });

  // Construct sides for preview calculation
  const previewPayload: PreviewMatchPayload | null = useMemo(() => {
    if (!sportKey || isCancelled) return null;

    // Case 1: Teams already generated by balancing engine
    if (
      teamSuggestion?.teams &&
      teamSuggestion.teams.length >= 2 &&
      teamSuggestion.teams[0].players.length > 0 &&
      teamSuggestion.teams[1].players.length > 0
    ) {
      return {
        sportKey,
        sides: [
          {
            sideKey: teamSuggestion.teams[0].sideKey || 'side_a',
            playerIds: teamSuggestion.teams[0].players.map((p) => p.userId),
          },
          {
            sideKey: teamSuggestion.teams[1].sideKey || 'side_b',
            playerIds: teamSuggestion.teams[1].players.map((p) => p.userId),
          },
        ],
      };
    }

    // Case 2: Split joined roster into 2 provisional sides if at least 2 players exist
    const joinedPlayers = roster?.joined || [];
    if (joinedPlayers.length >= 2) {
      const half = Math.ceil(joinedPlayers.length / 2);
      const sideAIds = joinedPlayers.slice(0, half).map((p) => p.userId);
      const sideBIds = joinedPlayers.slice(half).map((p) => p.userId);

      if (sideAIds.length > 0 && sideBIds.length > 0) {
        return {
          sportKey,
          sides: [
            { sideKey: 'side_a', playerIds: sideAIds },
            { sideKey: 'side_b', playerIds: sideBIds },
          ],
        };
      }
    }

    return null;
  }, [sportKey, teamSuggestion, roster]);

  // Live rating preview query hook
  const {
    data: previewData,
    isLoading: isPreviewLoading,
  } = useMatchRatingPreview(client, previewPayload);

  const preview: MatchPreviewResponse | null = (previewData as any)?.data || previewData || null;

  const isCalculating = isTeamSuggestionLoading || isPreviewLoading;
  const callerDeltas = preview?.callerHypotheticalDeltas;
  const isParticipantInPreview = Boolean(
    callerDeltas && typeof callerDeltas.win === 'number' && typeof callerDeltas.loss === 'number'
  );
  const hasValidSides = Boolean(
    preview &&
      preview.sideA &&
      typeof preview.sideA.winProbabilityPercent === 'number' &&
      preview.sideB &&
      typeof preview.sideB.winProbabilityPercent === 'number'
  );

  if (isCancelled) {
    return (
      <Card className={`border-border-subtle bg-card text-card-foreground shadow-xs overflow-hidden ${className}`}>
        <CardHeader className="pb-3 border-b border-border/40 bg-muted/20">
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-2">
              <Icon name="award" className="text-muted-foreground" size={16} />
              <CardTitle className="text-sm font-bold">What&apos;s at Stake?</CardTitle>
            </div>
            <Badge variant="outline" className="text-[10px]">Deactivated</Badge>
          </div>
        </CardHeader>
        <CardContent className="p-4 text-xs text-muted-foreground text-center">
          <p>This match is cancelled. Rating stakes and Elo updates are deactivated.</p>
        </CardContent>
      </Card>
    );
  }

  return (
    <Card className={`border-border-subtle bg-card text-card-foreground shadow-xs overflow-hidden ${className}`}>
      {/* Header */}
      <CardHeader className="pb-3 border-b border-border/40 bg-muted/20">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-2.5">
            <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-indigo-500/10 text-indigo-600 dark:text-indigo-400">
              <Icon name="trophy" size={16} />
            </div>
            <div>
              <CardTitle className="text-sm font-bold flex items-center gap-2">
                What&apos;s at Stake?
                <Badge variant="outline" className="text-[10px] font-semibold text-primary">
                  Prospective Elo
                </Badge>
              </CardTitle>
              <p className="text-xs text-muted-foreground">
                Predictive skill rating movements
              </p>
            </div>
          </div>

          {onExplainRatings && (
            <button
              type="button"
              onClick={onExplainRatings}
              className="flex items-center gap-1 text-xs font-semibold text-primary hover:text-primary-hover p-1 rounded-md hover:bg-muted transition-colors"
              title="Explain Elo Calculation Formula"
            >
              <Icon name="info" size={14} />
              <span className="hidden sm:inline">How Elo Works</span>
            </button>
          )}
        </div>
      </CardHeader>

      <CardContent className="p-4 sm:p-5 space-y-4">
        {/* Loading State */}
        {isCalculating && (
          <div className="flex flex-col items-center justify-center py-4 text-center space-y-2">
            <Icon name="spinner" size={20} className="animate-spin text-primary" />
            <p className="text-xs text-muted-foreground">
              Computing prospective Elo adjustments...
            </p>
          </div>
        )}

        {/* Not Enough Players State */}
        {!isCalculating && (!previewPayload || !preview || (!isParticipantInPreview && !hasValidSides)) && (
          <div className="rounded-xl border border-dashed border-border bg-muted/10 p-4 text-center text-xs space-y-1.5">
            <Icon name="users" size={20} className="mx-auto text-muted-foreground" />
            <p className="font-semibold text-foreground">
              Rating stakes activate once players register
            </p>
            <p className="text-muted-foreground max-w-xs mx-auto text-[11px]">
              Once at least two players are confirmed and balanced into teams, this widget will show prospective Elo gains and win probabilities.
            </p>
          </div>
        )}

        {/* Calculated Stakes Display */}
        {!isCalculating && preview && (isParticipantInPreview || hasValidSides) && (
          <div className="space-y-4">
            {/* Viewer Personal Elo Impact Hero Callout */}
            {isParticipantInPreview && callerDeltas ? (
              <div className="rounded-2xl border border-primary/20 bg-gradient-to-br from-primary/5 via-indigo-500/5 to-transparent p-4">
                <span className="text-[11px] font-bold uppercase tracking-wider text-primary block mb-2">
                  Your Rating Stakes For This Match
                </span>

                <div className="grid grid-cols-3 gap-2.5">
                  {/* Win Delta */}
                  <div className="rounded-xl border border-emerald-500/20 bg-emerald-500/10 p-3 text-center">
                    <span className="text-[11px] font-semibold text-emerald-800 dark:text-emerald-300 block">
                      Victory
                    </span>
                    <div className="mt-1 flex items-center justify-center gap-1 text-emerald-600 dark:text-emerald-400 font-black text-lg tabular-nums">
                      <Icon name="trending-up" size={16} className="shrink-0" />
                      <span>+{callerDeltas.win}</span>
                    </div>
                    <span className="text-[10px] text-emerald-700/70 dark:text-emerald-400/70 block mt-0.5">
                      Elo Gain
                    </span>
                  </div>

                  {/* Draw Delta */}
                  <div className="rounded-xl border border-slate-200 bg-slate-100/60 dark:border-slate-800 dark:bg-slate-800/40 p-3 text-center">
                    <span className="text-[11px] font-semibold text-slate-600 dark:text-slate-300 block">
                      Draw
                    </span>
                    <div className="mt-1 flex items-center justify-center gap-1 text-slate-700 dark:text-slate-300 font-black text-lg tabular-nums">
                      <Icon name="minus" size={16} className="shrink-0" />
                      <span>{callerDeltas.draw >= 0 ? `+${callerDeltas.draw}` : callerDeltas.draw}</span>
                    </div>
                    <span className="text-[10px] text-muted-foreground block mt-0.5">
                      Adjustment
                    </span>
                  </div>

                  {/* Loss Delta */}
                  <div className="rounded-xl border border-rose-500/20 bg-rose-500/10 p-3 text-center">
                    <span className="text-[11px] font-semibold text-rose-800 dark:text-rose-300 block">
                      Defeat
                    </span>
                    <div className="mt-1 flex items-center justify-center gap-1 text-rose-600 dark:text-rose-400 font-black text-lg tabular-nums">
                      <Icon name="trending-down" size={16} className="shrink-0" />
                      <span>{callerDeltas.loss}</span>
                    </div>
                    <span className="text-[10px] text-rose-700/70 dark:text-rose-400/70 block mt-0.5">
                      Elo Loss
                    </span>
                  </div>
                </div>
              </div>
            ) : (
              <div className="rounded-xl border border-border/80 bg-muted/30 p-3 text-xs text-muted-foreground flex items-center gap-2">
                <Icon name="sparkles" size={16} className="text-primary shrink-0" />
                <span>
                  You are viewing this match. Join the roster to calculate your personal rating gain/loss stakes.
                </span>
              </div>
            )}

            {/* Team Matchup Win Probability Bar */}
            {hasValidSides && (
              <div className="space-y-2 pt-1">
                <div className="flex items-center justify-between text-xs">
                  <div>
                    <span className="font-bold text-foreground">
                      {preview.sideA.sideKey === 'side_a' ? 'Team 1' : preview.sideA.sideKey}
                    </span>
                    {preview.sideA.teamRating !== undefined && (
                      <span className="text-[11px] text-muted-foreground ml-1.5 font-mono">
                        ({preview.sideA.teamRating} Elo)
                      </span>
                    )}
                  </div>
                  <div>
                    {preview.sideB.teamRating !== undefined && (
                      <span className="text-[11px] text-muted-foreground mr-1.5 font-mono">
                        ({preview.sideB.teamRating} Elo)
                      </span>
                    )}
                    <span className="font-bold text-foreground">
                      {preview.sideB.sideKey === 'side_b' ? 'Team 2' : preview.sideB.sideKey}
                    </span>
                  </div>
                </div>

                {/* Progress bar comparing win probabilities */}
                <div className="relative h-2.5 w-full overflow-hidden rounded-full bg-slate-200 dark:bg-slate-700 flex">
                  <div
                    className="h-full bg-gradient-to-r from-indigo-500 to-indigo-400 transition-all duration-500"
                    style={{ width: `${preview.sideA.winProbabilityPercent}%` }}
                  />
                  <div
                    className="h-full bg-gradient-to-r from-purple-500 to-purple-400 transition-all duration-500"
                    style={{ width: `${preview.sideB.winProbabilityPercent}%` }}
                  />
                </div>

                <div className="flex items-center justify-between text-[11px] font-extrabold tabular-nums">
                  <span className="text-indigo-600 dark:text-indigo-400">
                    {preview.sideA.winProbabilityPercent}% Win Expectancy
                  </span>
                  <span className="text-purple-600 dark:text-purple-400">
                    {preview.sideB.winProbabilityPercent}% Win Expectancy
                  </span>
                </div>
              </div>
            )}
          </div>
        )}
      </CardContent>
    </Card>
  );
}
